#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
AskQet — гарнитура вшивается в документ, а не подтягивается из сети.

ЧТО СЛУЧИЛОСЬ, И ЭТО ГЛАВНОЕ НА ЭТОМ ЛИСТЕ

  Руководство открылось у заказчика пустым. Текста нет — ни строки.

  Виноват @import. Он стоял первым правилом внутри <style>, и это верно
  по правилам CSS, но у него есть свойство, о котором я не подумал: он
  ЗАДЕРЖИВАЕТ ОТРИСОВКУ ВСЕЙ СТРАНИЦЫ. Браузер не рисует ничего, пока не
  разберётся со всеми таблицами стилей, а @import — ещё одна таблица,
  которую надо сходить и забрать. Есть сеть — задержка в сотню
  миллисекунд, её не видно. Нет сети, или запрос повис в прокси, или
  fonts.googleapis.com закрыт в контуре заказчика — и лист стоит белым,
  пока не выйдет таймаут. Не «шрифт заменился на запасной», а НИЧЕГО НЕ
  ВИДНО: ни текста, ни знака.

  Почему мои проверки молчали. Я снимал документ headless-хромом в этой
  машине, где сеть есть и прокси отвечает. Инструмент работал в самых
  добрых условиях, какие бывают, и потому подтверждал что угодно.
  Ошибка та же по природе, что была с hhea и с растеканием: мерка,
  поставленная в тепличные условия, показывает не то, что у читателя.

  Заодно вскрылось второе: документ и документом-то не был. Файл
  начинался прямо с <title> — ни doctype, ни <head>, ни объявления
  кодировки. Chromium достраивает скелет сам и угадывает UTF-8 по
  байтам; другой просмотрщик не обязан ни тому, ни другому, и кириллица
  у него становится кракозябрами. Скелет теперь печатается явно.

ЧТО СДЕЛАНО ВЗАМЕН

  Подсети Commissioner скачиваются один раз и кладутся ПРЯМО В CSS
  строками base64. Документ перестаёт зависеть от сети совсем: ни
  одного внешнего запроса, ни одного блокирующего ресурса. Открывается
  с флешки, из почты, из закрытого контура — одинаково.

  Берутся четыре подмножества — кириллица, расширенная кириллица,
  латиница и расширенная латиница (в ней живут казахские ә ğ ı ñ ö ş ü)
  — в трёх начертаниях: прямое 400, прямое 600 и наклонное 400.
  Полужирный наклон не берётся: в документе его нет.

  У каждого правила остаётся font-display: swap и родной unicode-range,
  так что браузер грузит только те куски, которые ему нужны на странице.

ЧЕГО ЭТОТ ЛИСТ НЕ РЕШАЕТ

  ЛИЦЕНЗИЮ. Commissioner идёт под SIL OFL, и OFL прямо разрешает
  встраивание в документы. Это чтение лицензии, а не заключение:
  проверять её заказчику с юристом, как и всё остальное право.

  ВЕС ФАЙЛА. Документ прибавляет около 280 КБ. Для руководства, которое
  открывают с диска и шлют почтой, это верный размен: лучше тяжелее на
  четверть мегабайта, чем пустой лист без сети.

Запуск:  python3 tools/webfont.py
Пишет:   tools/commissioner.css  (вшитая гарнитура, её читает book.py)
"""

import base64
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build import ROOT  # noqa: E402

FAMILY = "Commissioner"
API = "https://fonts.googleapis.com/css2?family=Commissioner:slnt,wght@"
# Прямое 400, прямое 600, наклонное 400. Полужирного наклона в документе нет.
FACES = ("0,400", "0,600", "-12,400")
# Кириллица, расширенная кириллица и обе латиницы: казахские ә ğ ı ñ ö ş ü
# лежат в расширенной, и без неё документ теряет ровно те буквы, ради
# которых гарнитура и выбиралась.
SUBSETS = ("cyrillic", "cyrillic-ext", "latin", "latin-ext")
UA = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/120 Safari/537.36")
OUT = "tools/commissioner.css"

RE_BLOCK = re.compile(r"/\* ([\w-]+) \*/\s*@font-face \{(.*?)\}", re.S)
RE_URL = re.compile(r"url\((https://[^)]+)\)")
RE_STYLE = re.compile(r"font-style:\s*([^;]+);")
RE_WEIGHT = re.compile(r"font-weight:\s*([^;]+);")
RE_RANGE = re.compile(r"unicode-range:\s*([^;]+);")


def fetch(url):
    """Забрать байты. Прокси и его корневой сертификат берутся из среды."""
    r = subprocess.run(["curl", "-sS", "-A", UA, url],
                       capture_output=True)
    if r.returncode:
        raise RuntimeError(r.stderr.decode("utf-8", "replace")[:200])
    return r.stdout


def faces():
    """Разбор ответа словолитни: начертание, диапазон и адрес файла."""
    out = []
    for q in FACES:
        css = fetch(API + q + "&display=swap").decode("utf-8")
        for name, body in RE_BLOCK.findall(css):
            if name not in SUBSETS:
                continue
            out.append(dict(subset=name,
                            style=RE_STYLE.search(body).group(1).strip(),
                            weight=RE_WEIGHT.search(body).group(1).strip(),
                            rng=RE_RANGE.search(body).group(1).strip(),
                            url=RE_URL.search(body).group(1)))
    return out


def rule(f, blob):
    """Одно правило со шрифтом внутри. Внешних адресов не остаётся."""
    b64 = base64.b64encode(blob).decode("ascii")
    return (f"/* {f['subset']} */\n"
            f"@font-face {{\n"
            f"  font-family: '{FAMILY}';\n"
            f"  font-style: {f['style']};\n"
            f"  font-weight: {f['weight']};\n"
            f"  font-display: swap;\n"
            f"  src: url(data:font/woff2;base64,{b64}) format('woff2');\n"
            f"  unicode-range: {f['rng']};\n"
            f"}}\n")


if __name__ == "__main__":
    F = faces()
    parts, tot = [], 0
    print(f"ВШИВАНИЕ {FAMILY.upper()} — документ перестаёт зависеть от сети\n")
    print(f"{'подмножество':<16}{'начертание':<16}{'вес':>5}{'вес файла':>12}")
    for f in F:
        blob = fetch(f["url"])
        tot += len(blob)
        parts.append(rule(f, blob))
        print(f"{f['subset']:<16}{f['style']:<16}{f['weight']:>5}"
              f"{len(blob) / 1024:>9.1f} КБ")

    head = (
        "/* AskQet — Commissioner, вшитый в документ.\n"
        "   Собран tools/webfont.py; правки вносить туда, а не сюда.\n"
        "\n"
        "   Прежде гарнитура тянулась через @import из сети, и это дважды\n"
        "   неверно. Во-первых, @import задерживает отрисовку ВСЕЙ\n"
        "   страницы: без сети браузер показывает пустой лист, а не текст\n"
        "   запасным шрифтом. Во-вторых, руководство обязано открываться\n"
        "   там, где сети нет вовсе — с флешки, из почты, в закрытом\n"
        "   контуре. Теперь внешних запросов не остаётся ни одного.\n"
        "\n"
        "   Лицензия SIL OFL встраивание в документы разрешает; проверка\n"
        "   права — за юристом заказчика, а не за этим файлом. */\n\n")
    with open(os.path.join(ROOT, OUT), "w", encoding="utf-8") as fh:
        fh.write(head + "\n".join(parts))

    size = os.path.getsize(os.path.join(ROOT, OUT))
    print(f"\n{len(F)} начертаний · {tot / 1024:.0f} КБ шрифта · "
          f"{size / 1024:.0f} КБ в CSS")
    print(f"записано: {OUT}\n")
    print("документ теперь открывается без сети: ни одного внешнего "
          "запроса,\nни одного ресурса, задерживающего отрисовку.")
