def fit_accent(paper_hex, ink_hex, C, Hd):
    """Светлота акцента не назначается, а решается — во всех мирах одинаково.

    Иначе сравнение нечестное: у книги акцент подобран замером в color2, а
    у остальных семи я бы поставил его на глаз, и разница вышла бы не
    между подходами, а между тем, где я старался.

    Правило то же, что вывел color2: берётся КРАЙНЯЯ ступень, ещё держащая
    текстовый порог. На светлой бумаге крайняя — самая светлая, на тёмной
    — самая тёмная; в обоих случаях это предел, за которым акцент сползает
    к чернилам и перестаёт быть акцентом.
    """
    light = wcag(paper_hex, "#000000") > wcag(paper_hex, "#FFFFFF")
    good = []
    for i in range(71):
        L = 0.20 + i * 0.01
        h = hex_of(L, C, Hd)
        if wcag(h, paper_hex) < TEXT:
            continue
        if min(de_ok(simulate(h, k), simulate(ink_hex, k))
               for k in CVD) < MIN_DE:
            continue
        good.append((L, h))
    if not good:
        return hex_of(0.50, C, Hd), False
    return (max(good)[1] if light else min(good)[1]), True


def palette(paper, ink, accent):
    """Пять красок мира. Полутон и линейка выводятся, а не назначаются."""
    P = dict(paper=hex_of(*paper), ink=hex_of(*ink))
    for name, t in (("muted", 0.50), ("line", 0.25)):
        L = paper[0] + (ink[0] - paper[0]) * t
        C = paper[1] + (ink[1] - paper[1]) * t
        Hd = paper[2] if abs(paper[2] - ink[2]) > 180 else \
            paper[2] + (ink[2] - paper[2]) * t
        P[name] = hex_of(L, C, Hd)
    P["has_accent"] = accent is not None
    if accent:
        P["accent"], P["fit"] = fit_accent(P["paper"], P["ink"],
                                           accent[1], accent[2])
    else:
        P["accent"], P["fit"] = P["ink"], True
    return P


