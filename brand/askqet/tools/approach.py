"""
AskQet — восемь цветовых подходов к знаку. Разные миры, а не оттенки.

Признание, с которого надо начать. Три прежних листа отвечали на три
разных вопроса, но все три сидели в ОДНОМ цветовом мире: кремовая бумага,
тёплые серые чернила, одна холодная синяя деталь. color.py спрашивал,
куда положить акцент. color2.py чинил его светлоту. ways.py раскладывал
готовую палитру по носителям. Ни один не спрашивал главного — а тот ли
это мир вообще. Здесь спрашивается только это.

Что считается подходом, а что нет

  Подход — не оттенок акцента. Подход задаёт ТРИ вещи разом: чем бумага,
  чем чернила и есть ли акцент вообще. Отсюда следует температура, вес,
  и то, на что знак похож — на книгу, на бланк, на печать, на терминал.
  Смена акцента с синего на зелёный подходом не является: мир остаётся
  тот же.

  Поэтому среди восьми есть два безакцентных. Отсутствие акцента — тоже
  подход, и для справочника по налогам он не хуже прочих: бланк не бывает
  нарядным.

Как это построено

  Каждый мир задан ТРЕМЯ точками в OKLCH — бумага, чернила, акцент. Всё
  остальное выведено: полутон стоит посередине между бумагой и чернилами
  по светлоте, линейка — на четверти пути от бумаги. Ни одно значение не
  подобрано на глаз, и миры поэтому сравнимы между собой: у них одинаково
  устроены производные.

Чем это меряется

  Контраст чернил к бумаге — читаемость набора, порог текстовый 4.5.
  Контраст акцента к бумаге — акцент работает ссылкой, тот же порог.
  ΔE акцента к чернилам — отходит ли акцент от набора или только
  подкрашивает его; это та самая претензия, из-за которой берлинская
  лазурь оказалась слабой.
  Дальтонизм — расходятся ли акцент и чернила при трёх формах.
  Одна краска — сколько мир теряет, когда цвета нет вовсе.

  Судится всё это НЕ на знаке: набор занимает несравнимо больше места, чем
  марка. Каждый мир показан полосой справочника, и решать надо по ней.

  Оговорка, появившаяся позже: здесь стояло «на знаке акцента один процент
  площади, там сгодится любой». Это было верно, пока ляссе было вырезом на
  конце хвоста. Ляссе стало лентой, и доля акцента на знаке — шесть
  процентов с лишним. Вывод листа не меняется, а довод пришлось убрать.

Запуск:  python3 tools/approach.py
Пишет:   logo/approach/, tools/approach.json
"""

