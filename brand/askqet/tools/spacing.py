def gap_between_lines(size, lead, width):
    """Просвет: высота белой полосы между строками набора.

    Меряется по строкам растра: строка кадра либо несёт краску, либо
    нет. Между строками текста идут подряд чистые — их и считаем. Берётся
    ТИПИЧНАЯ длина промежутка, а не наибольшая: наибольшая приходится на
    строку без выносных и врёт в большую сторону.
    """
    h = int(PAD * 2 + 8 * size * lead)
    p = write("logo/spacing/_para.html", para_plate(size, lead, width))
    px, w, hh = shoot([dict(key="p", path=os.path.join(ROOT, p),
                            w=int(width + PAD * 2), h=h)])["p"]
    ink = binary(px, w, hh)
    rows = [any(ink[y * w + x] for x in range(w)) for y in range(hh)]
    if True not in rows:
        os.remove(os.path.join(ROOT, p))
        return dict(gap=0, runs=[], lines=0)
    first = rows.index(True)
    last = hh - 1 - rows[::-1].index(True)
    runs, cur = [], 0
    for y in range(first, last + 1):
        if rows[y]:
            if cur:
                runs.append(cur)
                cur = 0
        else:
            cur += 1
    os.remove(os.path.join(ROOT, p))
    runs.sort()
    return dict(gap=runs[len(runs) // 2] if runs else 0,
                runs=runs, lines=len(runs) + 1)


def browser(html, script):
    """Замер вёрстки: то, что считает сам движок, а не я по формуле."""
    p = write("logo/spacing/_m.html", html)
    js = ("const {chromium} = require('playwright');\n"
          "(async () => {\n"
          "  const b = await chromium.launch();\n"
          "  const pg = await b.newPage({viewport:{width:1400,height:900}});\n"
          "  await pg.goto('file://' + process.argv[2]);\n"
          "  await pg.waitForTimeout(700);\n"
          f"  const r = await pg.evaluate(() => {{{script}}});\n"
          "  console.log(JSON.stringify(r));\n"
          "  await b.close();\n"
          "})();\n")
    tmp = os.environ.get("TMPDIR", "/tmp")
    jsp = os.path.join(tmp, "sp.js")
    with open(jsp, "w", encoding="utf-8") as f:
        f.write(js)
    env = dict(os.environ, NODE_PATH="/opt/node22/lib/node_modules")
    r = subprocess.run(["node", jsp, os.path.join(ROOT, p)],
                       capture_output=True, text=True, env=env, cwd=ROOT)
    os.remove(os.path.join(ROOT, p))
    if r.returncode:
        raise RuntimeError(r.stderr[-400:])
    return json.loads(r.stdout.strip().splitlines()[-1])


