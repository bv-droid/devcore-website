def per_line(size, lead, width):
    """Сколько знаков ложится в строку НА САМОМ ДЕЛЕ, вёрсткой.

    Первый заход считал это делением меры на среднюю ширину знака — то
    есть делил на то, на что перед этим умножил, и честно получал ровно
    заданные 66 на обоих языках. Круг, а не замер. Настоящий ответ даёт
    вёрстка: абзац ставится в меру, считаются его строки, знаки делятся
    на строки. Здесь работают пробелы и длина слов, и языки расходятся.
    """
    html = (f'<style>{font_css()}html,body{{margin:0;background:#fff}}'
            f'.p{{font-family:"Commissioner";font-weight:400;'
            f'font-size:{size:.2f}px;line-height:{lead};'
            f'width:{width:.2f}px}}</style>'
            f'<div class="p" id="ru">{RU}</div>'
            f'<div class="p" id="kz">{KZ}</div>')
    return browser(html, """
      const out = {};
      for (const id of ['ru','kz']) {
        const e = document.getElementById(id);
        const lh = parseFloat(getComputedStyle(e).lineHeight);
        const lines = Math.round(e.getBoundingClientRect().height / lh);
        out[id] = {lines: lines, chars: e.textContent.length / lines};
      }
      return out;""")


def measure_for(size, lead, target, lo=520.0, hi=1400.0):
    """Мера строки ищется ВЁРСТКОЙ, а не умножением.

    Умножение средней ширины знака на желаемое число знаков промахивается,
    и сильно: оно считает строку сплошной, а вёрстка рвёт её по словам и
    оставляет справа рваный край. При мере 996 px умножение обещало 66
    знаков, а легло 56. Поэтому ширина подбирается делением пополам: на
    каждом шаге абзац действительно верстается и его строки считаются.

    Ищется по РУССКОМУ: он длиннее казахского на нашем тексте, и мера,
    подобранная по нему, казахскому тесной не будет. Что получилось у
    казахского — печатается рядом, а не подгоняется.
    """
    best = None
    for _ in range(9):
        mid = (lo + hi) / 2
        r = per_line(size, lead, mid)
        got = r["ru"]["chars"]
        if best is None or abs(got - target) < abs(best[1] - target):
            best = (mid, got, r)
        if got < target:
            lo = mid
        else:
            hi = mid
    return dict(px=best[0], chars=best[1], both=best[2])


def sheet(rows, floor):
    """Ступени рядом: два блока и пустота между ними, в масштабе."""
    pad, colw, gap, bh = 30.0, 116.0, 22.0, 40.0
    o, x, hmax = [], pad, 0.0
    for r in rows:
        px, sep = r["px"], r["role"] == "разделяет"
        col = INK if sep else MUTED
        y = pad + 20
        o.append(f'<text x="{n(x)}" y="{n(pad + 10)}" '
                 f'font-family="ui-monospace,monospace" font-size="10" '
                 f'fill="{MUTED}">{r["name"]}</text>')
        for k in range(2):
            o.append(f'<rect x="{n(x)}" y="{n(y)}" width="{n(colw)}" '
                     f'height="{n(bh)}" fill="{col}" opacity="0.9"/>')
            y += bh + (px if k == 0 else 0)
        o.append(f'<line x1="{n(x - 9)}" y1="{n(pad + 20 + bh)}" '
                 f'x2="{n(x - 9)}" y2="{n(pad + 20 + bh + px)}" '
                 f'stroke="{ACCENT if sep else LINE}" stroke-width="2"/>')
        o.append(f'<text x="{n(x)}" y="{n(y + 16)}" '
                 f'font-family="ui-monospace,monospace" font-size="10" '
                 f'fill="{ACCENT if sep else MUTED}">{px:.0f} px'
                 f'{"" if sep else " · внутри"}</text>')
        hmax = max(hmax, y + 22)
        x += colw + gap
    Wd, Hh = x - gap + pad, hmax + pad
    # Пол печатается на самом листе: без него читатель не увидит, чем
    # серые ступени отличаются от чёрных.
    o.append(f'<text x="{n(pad)}" y="{n(Hh - 8)}" '
             f'font-family="ui-monospace,monospace" font-size="10" '
             f'fill="{MUTED}">пол — просвет между строками {floor} px; '
             f'пустота ниже него читается как «внутри блока»</text>')
    return svg(f'  <rect width="{n(Wd)}" height="{n(Hh)}" fill="{PAPER}"/>\n'
               f'  {"".join(o)}\n', box=(Wd, Hh),
               title="AskQet — ступени отступа")


