def fit_line(pts):
    """Прямая по методу наименьших квадратов: y = a + k·x."""
    m = len(pts)
    sx = sum(x for x, _ in pts)
    sy = sum(y for _, y in pts)
    sxx = sum(x * x for x, _ in pts)
    sxy = sum(x * y for x, y in pts)
    k = (m * sxy - sx * sy) / (m * sxx - sx * sx)
    return (sy - k * sx) / m, k


def blur_verdict():
    """Годится ли растекание в мерку отступа. Считается из записи."""
    a, k = fit_line(BLUR_RECORD)
    worst = max(abs(a + k * g - b) for g, b in BLUR_RECORD)
    # Коэффициент 1/2 означает: мерка пересказывает сам отступ. Допуск
    # взят широким нарочно — вывод не должен держаться на третьем знаке.
    return dict(a=a, k=k, worst=worst,
                trivial=abs(k - 0.5) < 0.02 and worst < 1.0)


