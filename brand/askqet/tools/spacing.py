    A = advance(size)
    naive = CHARS_AIM * A["ru"]                  # умножение — для сравнения
    MF = measure_for(size, lead, CHARS_AIM)
    meas = MF["px"]
    PL = MF["both"]
    # Просвет меряется на УЗКОЙ плашке: он от ширины колонки не зависит,
    # а строк на узкой больше, и медиана берётся не с трёх промежутков.
    G = gap_between_lines(size, lead, 420.0)
    floor = G["gap"]

    rows = [dict(k=k, name=nm, slug=sl, px=round(k * base, 1),
                 role=("разделяет" if k * base > floor else "внутри блока"))
            for k, nm, sl in CAND]
    write("logo/spacing/steps.svg", sheet(rows, floor))

    with open(os.path.join(ROOT, "tools/spacing.json"), "w",
              encoding="utf-8") as f:
        json.dump(dict(base=base, size=size, lead=lead, floor=floor,
                       blur=BV, blur_record=[list(r) for r in BLUR_RECORD],
                       steps=rows,
                       measure=dict(px=meas, naive=naive,
                                    adv_ru=A["ru"], adv_kz=A["kz"],
                                    chars_ru=PL["ru"]["chars"],
                                    chars_kz=PL["kz"]["chars"],
                                    lines_ru=PL["ru"]["lines"],
                                    lines_kz=PL["kz"]["lines"],
                                    aim=CHARS_AIM, lo=CHARS_LO, hi=CHARS_HI)),
                  f, ensure_ascii=False, indent=1)

    print("РАСТЕКАНИЕ В МЕРКУ ОТСТУПА НЕ ГОДИТСЯ — и это главный вывод\n")
    print("я собирался отбирать ступени тем же растеканием, что вело весь "
          "проект.\nПрогон дал складную таблицу. Потом я подогнал по ней "
          "прямую:\n")
    print(f"    сцепление = {BV['a']:.2f} + {BV['k']:.4f} × отступ, "
          f"худшее отклонение {BV['worst']:.2f} шага\n")
    if BV["trivial"]:
        print("коэффициент ровно ОДНА ВТОРАЯ: растекание закрывает зазор с "
              "двух сторон\nпо пикселю за шаг. «Сцепление» — это сам отступ "
              "пополам плюс постоянная.\nМерка пересказывает число, которое "
              "я в неё положил, и о группировке\nне знает ничего. Такую не "
              "чинят, её выбрасывают.\n")
    else:
        print("подгонка не легла — вывод о негодности мерки надо "
              "пересмотреть.\n")
    print("растекание работало на очках букв и на мелком знаке, где решала "
          "ФОРМА.\nОтступ — прямоугольная пустота, формы в нём нет, и "
          "заливка вырождается\nв арифметику.\n\n")

    print("ЧТО ОСТАЛОСЬ ЗАМЕРОМ — просвет между строками\n")
    print(f"  {'строка: кегль на интерлиньяж':<34}{base:>8.1f} px   "
          f"следствие принятого")
    print(f"  {'просвет между строками':<34}{floor:>8} px   ЗАМЕР")
    print(f"  {'строк в замеренном абзаце':<34}{G['lines']:>8}\n")
    print("просвет — ПОЛ отступа: пустота меньше него читается как «внутри\n"
          "абзаца», потому что ровно такая пустота внутри абзаца и стоит.\n")

    print("СТУПЕНИ — ряд решение, отбор замер\n")
    print(f"  {'ступень':<16}{'долей':>7}{'px':>8}   роль")
    for r in rows:
        print(f"  {r['name']:<16}{r['k']:>7.2f}{r['px']:>8.1f}   {r['role']}")
    sep = [r for r in rows if r["role"] == "разделяет"]
    ins = [r for r in rows if r["role"] != "разделяет"]
    print(f"\nразделяют {len(sep)}: " + " · ".join(f"{r['px']:.0f}"
                                                  for r in sep))
    if ins:
        print("внутри блока " + ", ".join(r["name"] for r in ins)
              + f" — они не больше просвета {floor} px,\nи разделить ими "
                "нельзя. Это отступы ВНУТРИ блока: между строкой таблицы\nи "
                "соседней, между подписью и полем.")
    print("\nпочему ряд крупный, а не такой же мелкий, как у кеглей: кегли "
          "сравнивают\nрядом, в одной строке, а отступы — через целый блок "
          "текста, и мелкая\nразница туда не доживает. Замера под это нет; "
          "сказано как решение.\n\n")

    print("МЕРА СТРОКИ — замер и заимствование, названные раздельно\n")
    print(f"  {'средняя ширина знака, русский':<34}{A['ru']:>8.2f} px   замер")
    print(f"  {'средняя ширина знака, казахский':<34}{A['kz']:>8.2f} px   "
          f"замер")
    print(f"  {'знаков в строке':<34}{CHARS_AIM:>8}      "
          f"ЗАИМСТВОВАНО ({CHARS_LO}–{CHARS_HI})")
    print(f"  {'мера строки':<34}{meas:>8.0f} px   ПОДОБРАНА вёрсткой\n")
    print(f"умножение средней ширины на 66 давало {naive:.0f} px и промах: "
          f"оно считает\nстроку сплошной, а вёрстка рвёт её по словам и "
          f"оставляет рваный край.\nПоэтому ширина подобрана делением "
          f"пополам — на каждом шаге абзац\nдействительно верстается и "
          f"строки считаются.\n")
    print(f"  {'русский':<16}{PL['ru']['lines']:>4} строк"
          f"{PL['ru']['chars']:>9.0f} знаков в строке")
    print(f"  {'казахский':<16}{PL['kz']['lines']:>4} строк"
          f"{PL['kz']['chars']:>9.0f} знаков в строке")
    okk = all(CHARS_LO <= v <= CHARS_HI
              for v in (PL["ru"]["chars"], PL["kz"]["chars"]))
    print("\n" + ("оба языка ложатся в норму." if okk else
                  "ОДИН ИЗ ЯЗЫКОВ ВЫШЕЛ ИЗ НОРМЫ — меру надо править."))
    print("\nнорма 45–75 знаков — типографская практика, а не мой замер. "
          "Проверить её\nможно только на читателях; здесь она названа "
          "заимствованной и не выдана\nза измеренную.")
