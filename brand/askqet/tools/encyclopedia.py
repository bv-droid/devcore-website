PAD = 26.0
ASC, XH, DESC = 72.0, 52.0, 20.0
BLOCK = ASC + LEAD + DESC


def tracked(word, sp, target):
    """Разрядка до заданной ширины: слово из трёх букв — два просвета."""
    _, w = L.line(word, sp)
    return (target - w) / (len(word) - 1)


def lines(sp1, sp2, even=False, tail=""):
    """Две строки. even — обе разогнаны до общей ширины."""
    _, w1 = L.line("ask", sp1)
    _, w2 = L.line("qet", sp2)
    if tail:
        w1 += tail_width(sp1)
    t1 = t2 = 0.0
    if even:
        target = max(w1, w2)
        t1, t2 = tracked("ask", sp1, target - (tail_width(sp1) if tail else 0)), \
            tracked("qet", sp2, target)
        _, w1 = L.line("ask", sp1, t1)
        _, w2 = L.line("qet", sp2, t2)
        if tail:
            w1 += tail_width(sp1)
    b1, _ = L.line("ask", sp1, t1, INK)
    b2, _ = L.line("qet", sp2, t2, INK)
    if tail:
        b1 += hyphen(sp1, w1 - tail_width(sp1))
    return b1, b2, max(w1, w2), w1, w2


# ── Дефис переноса ───────────────────────────────────────────────────────────
#
# Перенос — единственный знак препинания, который ставит сама колонка, а не
# автор. Длина взята от роста строчных, высота — по оптической середине
# строчной, чуть выше геометрической: на базовую дефис смотрится провисшим.

def tail_width(sp):
    return XH * 0.50 * sp["wd"]


def hyphen(sp, x0):
    y = -XH * 0.47
    w = XH * 0.38 * sp["wd"]
    st = sp["st"] * 0.86
    x = x0 + XH * 0.09 * sp["wd"]
    return (f'<rect x="{n(x)}" y="{n(y - st / 2)}" width="{n(w)}" '
            f'height="{n(st)}" fill="{INK}"/>')


def rule(x0, x1, y, st, k=0.12):
    return (f'<rect x="{n(x0)}" y="{n(y - st * k / 2)}" width="{n(x1 - x0)}" '
            f'height="{n(st * k)}" fill="{INK}"/>')


def plate(sp1, sp2, even=False, tail="", mid=False, head=False):
    b1, b2, w, w1, w2 = lines(sp1, sp2, even, tail)
    st = (sp1["st"] + sp2["st"]) / 2
    top = PAD + ASC
    W, H = w + PAD * 2, BLOCK + PAD * 2
    o = [f'<g transform="translate({n(PAD)},{n(top)})">{b1}</g>',
         f'<g transform="translate({n(PAD)},{n(top + LEAD)})">{b2}</g>']
    if mid:
        o.append(rule(PAD, PAD + w, top + (LEAD - XH) / 2, st, 0.14))
    if head:
        o.append(rule(PAD, PAD + w, PAD - ASC * 0.17, st, 0.16))
        o.append(rule(PAD, PAD + w, PAD + BLOCK + ASC * 0.13, st, 0.16))
    return svg(f'  <rect width="{n(W)}" height="{n(H)}" fill="{PAPER}"/>\n'
               f'  {"".join(o)}\n', box=(W, H), title="AskQet")


